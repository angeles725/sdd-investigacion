package archtest

import "testing"

func TestGeneratedHeaderIsExempt(t *testing.T) {
	generatedHeader := "// Code generated by tool; DO NOT EDIT.\n\npackage p\n"
	r := check(t, map[string]string{"g.go": generatedHeader + gen(500), "ok.go": gen(1)}, "")
	if r.Generated != 1 || r.Scanned != 1 || r.Over != 0 || len(r.Violations) != 0 {
		t.Errorf("got %+v", r)
	}
}

func TestGeneratedLineAfterPackageClauseIsNotExempt(t *testing.T) {
	src := "package p\n\n// Code generated by tool; DO NOT EDIT.\n" + gen(250)
	r := check(t, map[string]string{"g.go": src}, "")
	if r.Generated != 0 || r.Over != 1 || len(r.Violations) != 1 {
		t.Errorf("got %+v", r)
	}
}

func TestHeaderWithoutDoNotEditIsNotExempt(t *testing.T) {
	src := "// Code generated by tool.\npackage p\n" + gen(250)
	r := check(t, map[string]string{"g.go": src}, "")
	if r.Generated != 0 || r.Over != 1 {
		t.Errorf("got %+v", r)
	}
}

func TestGeneratedListedInDebtIsNotProduction(t *testing.T) {
	generatedHeader := "// Code generated by tool; DO NOT EDIT.\npackage p\n"
	debt := "g.go 300 legacy long enough reason\n"
	r := check(t, map[string]string{"g.go": generatedHeader + gen(300), "ok.go": gen(1)}, debt)
	want := "g.go: listed but not a production Go file in this tree. Delete this line from modularity-debt.txt" + moveHintGone + "g.go 300 legacy long enough reason"
	if len(r.Violations) != 1 || r.Violations[0] != want {
		t.Errorf("violations = %q, want [%q]", r.Violations, want)
	}
}
