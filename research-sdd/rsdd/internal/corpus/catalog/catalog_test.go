func TestLessNum(t *testing.T) {
	big := strings.Repeat("9", 40)
	for _, tt := range []struct {
		a, b string
		less bool
	}{
		{"2", "10", true}, {"10", "2", false}, {"1", "2", true}, {"2", "1", false}, {"7", "7", false},
		{"19", "21", true}, {"21", "19", false}, {big, "1" + big, true}, {"1" + big, big, false},
	} {
		if got := lessNum(tt.a, tt.b); got != tt.less {
			t.Errorf("lessNum(%q, %q) = %v", tt.a, tt.b, got)
		}
	}
}

func TestIsPySpace(t *testing.T) {
	in := []rune{'\t', '\n', '\v', '\f', '\r', 0x1c, 0x1d, 0x1e, 0x1f, ' ', 0x85, 0xa0, 0x1680, 0x2000, 0x2005, 0x200a, 0x2028, 0x2029, 0x202f, 0x205f, 0x3000}
	out := []rune{'a', '0', 0x08, 0x0e, 0x1b, 0x21, 0x84, 0x86, 0x9f, 0xa1, 0x167f, 0x1681, 0x1fff, 0x200b, 0x200c, 0x202a, 0x202e, 0x2030, 0x205e, 0x2060, 0x2fff, 0x3001, 0xfeff}
	for _, r := range in {
		if !isPySpace(r) {
			t.Errorf("isPySpace(%U) = false", r)
		}
	}
	for _, r := range out {
		if isPySpace(r) {
			t.Errorf("isPySpace(%U) = true", r)
		}
	}
}

func TestTitlePattern(t *testing.T) {
	for _, tt := range []struct{ line, want string }{
		{"# Block 1 — x", "x"},
		{"# Bloque 2 - x", "x"},
		{"# Block　1 — x　 ", "x"},
		{"# Block 1 — a — b", "a — b"},
		{"# Block 10-11 — x", "11 — x"},
		{"# Block 1 —  ", " "},
		{"# Block ٢ — d", "d"},
		{"# Block1 —x", "x"},
		{"#Block 1 — x", "x"},
	} {
		m := titleRE.FindStringSubmatch(tt.line)
		if m == nil || m[1] != tt.want {
			t.Errorf("titleRE(%q) = %q, want %q", tt.line, m, tt.want)
		}
	}
	for _, line := range []string{"# Block 1 —", "# Block — x", "# block 1 — x", "# Block 1 – x", "# Foo 1 — x", "x # Block 1 — x", "## Block 1 — x"} {
		if m := titleRE.FindStringSubmatch(line); m != nil {
			t.Errorf("titleRE(%q) matched %q", line, m)
		}
	}
}

func TestTitleReading(t *testing.T) {
	long := strings.Repeat("filler line\n", 2000)
	for name, tt := range map[string]struct{ body, want string }{
		"clean":          {"# Block 1 — Plain\n", "Plain"},
		"crlf":           {"# Block 1 — Plain\r\nbody\r\n", "Plain"},
		"lone cr":        {"first\r# Block 1 — After\rrest", "After"},
		"cr at eof":      {"# Block 1 — End\r", "End"},
		"no newline":     {"# Block 1 — End", "End"},
		"raw fallback":   {"# Random heading  \n# Block 1 — later\n", "Random heading"},
		"fallback trims": {"# 　 spaced  \n", "spaced"},
		"empty heading":  {"# \n", ""},
		"after filler":   {long + "# Block 1 — Deep\n", "Deep"},
		"untitled":       {"body\n#Block 1 — nope\n", "(untitled)"},
		"empty file":     {"", "(untitled)"},
		"only newlines":  {"\n\n\r\n\r", "(untitled)"},
		"bom hides it":   {"\xef\xbb\xbf# Block 1 — x\n", "(untitled)"},
		"hash only":      {"#\n# \n", ""},
		"double hash":    {"## Block 1 — x\n", "(untitled)"},
	} {
		t.Run(name, func(t *testing.T) {
			p := filepath.Join(t.TempDir(), "f.md")
			if err := os.WriteFile(p, []byte(tt.body), 0o644); err != nil {
				t.Fatal(err)
			}
			if got, err := blockTitle(p); err != nil || got != tt.want {
				t.Errorf("blockTitle = %q, %v; want %q", got, err, tt.want)
			}
		})
	}
}

// Bytes after the title line are never read (declared deviation: Python decodes a whole chunk), but an invalid line
// before it, or any invalid line when there is no title, fails.
func TestTitleKeepsReadingOnlyUpToTheTitle(t *testing.T) {
	for name, tt := range map[string]struct {
		body    string
		wantErr bool
	}{
		"invalid after the title":  {"# Block 1 — ok\n\xff\n", false},
		"invalid before the title": {"\xff\n# Block 1 — ok\n", true},
		"invalid in the title":     {"# Block 1 — o\xffk\n", true},
		"invalid no title, last":   {"body\n\xff", true},
		"invalid no title, mid":    {"a\r\xfe\rb\n", true},
		"truncated rune at eof":    {"# Block 1 \xe2\x80", true},
	} {
		t.Run(name, func(t *testing.T) {
			p := filepath.Join(t.TempDir(), "f.md")
			if err := os.WriteFile(p, []byte(tt.body), 0o644); err != nil {
				t.Fatal(err)
			}
			_, err := blockTitle(p)
			if (err != nil) != tt.wantErr {
				t.Errorf("err = %v, wantErr %v", err, tt.wantErr)
			}
			if err != nil && !strings.Contains(err.Error(), p) {
				t.Errorf("error %q does not name the file", err)
			}
		})
	}
}

func TestFailures(t *testing.T) {
	t.Run("missing root", func(t *testing.T) {
		rc, out, errb := run(t, "/work", filepath.Join(t.TempDir(), "nope"))
		if rc != cli.ExitOperational || out != "" || !strings.HasPrefix(errb, "rsdd corpus catalog: ") {
			t.Errorf("rc=%d out=%q err=%q", rc, out, errb)
		}
	})
	t.Run("root is a file", func(t *testing.T) {
		f := filepath.Join(t.TempDir(), "f")
		write(t, filepath.Dir(f), "f", "x")
		if rc, out, _ := run(t, "/work", f); rc != cli.ExitOperational || out != "" {
			t.Errorf("rc=%d out=%q", rc, out)
		}
	})
	t.Run("catalog is a directory", func(t *testing.T) {
		d := t.TempDir()
		write(t, d, "p-block1.md", "# Block 1 — x\n")
		if err := os.Mkdir(filepath.Join(d, "CATALOG.md"), 0o755); err != nil {
			t.Fatal(err)
		}
		if rc, out, errb := run(t, "/work", d); rc != cli.ExitOperational || out != "" || errb == "" {
			t.Errorf("rc=%d out=%q err=%q", rc, out, errb)
		}
	})
	t.Run("dangling link named like a block", func(t *testing.T) {
		d := t.TempDir()
		if err := os.Symlink(filepath.Join(d, "gone"), filepath.Join(d, "p-block1.md")); err != nil {
			t.Fatal(err)
		}
		if rc, _, _ := run(t, "/work", d); rc != cli.ExitOperational {
			t.Errorf("rc=%d", rc)
		}
		if _, err := os.Stat(filepath.Join(d, "CATALOG.md")); err == nil {
			t.Errorf("CATALOG.md written")
		}
	})
	t.Run("name that is not valid UTF-8", func(t *testing.T) {
		d := t.TempDir()
		write(t, d, "p-block1.md", "# Block 1 — x\n")
		write(t, d, "p\xff-block2.md", "# Block 2 — y\n")
		write(t, d, "CATALOG.md", "OLD\n")
		rc, _, errb := run(t, "/work", d)
		if rc != cli.ExitOperational || !strings.Contains(errb, "not valid UTF-8") {
			t.Errorf("rc=%d err=%q", rc, errb)
		}
		if got := catalogOf(t, d); got != "OLD\n" {
			t.Errorf("CATALOG.md touched: %q", got)
		}
	})
	t.Run("invalid name that is not a block is ignored", func(t *testing.T) {
		d := t.TempDir()
		write(t, d, "p-block1.md", "# Block 1 — x\n")
		write(t, d, "p-block2-\xff.md", "# Block 2 — y\n")
		if rc, out, errb := run(t, "/work", d); rc != 0 || out != "CATALOG.md regenerated: 1 blocks.\n" {
			t.Errorf("rc=%d out=%q err=%q", rc, out, errb)
		}
	})
	t.Run("unreadable root counts as empty", func(t *testing.T) {
		d := t.TempDir()
		write(t, d, "p-block1.md", "# Block 1 — x\n")
		if err := os.Chmod(d, 0o300); err != nil {
			t.Fatal(err)
		}
		defer os.Chmod(d, 0o755)
		if f, err := os.Open(d); err == nil {
			f.Close()
			t.Skip("directory is readable anyway (running as root?)")
		}
		rc, out, _ := run(t, "/work", d)
		if rc != 0 || out != "CATALOG.md regenerated: 0 blocks.\n" {
			t.Errorf("rc=%d out=%q", rc, out)
		}
	})
}
